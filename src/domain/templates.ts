import type { TemplateDef, TextStyle, ShapeStyle, TemplateElement } from './types';

const text = (
  t: Partial<TextStyle> & { text: string; x: number; y: number; width: number; height?: number },
): TemplateElement => ({
  type: 'text',
  x: t.x,
  y: t.y,
  width: t.width,
  height: t.height ?? Math.max(40, (t.fontSize ?? 32) * 1.3),
  content: { text: t.text },
  style: {
    fontFamily: t.fontFamily ?? 'Inter',
    fontSize: t.fontSize ?? 32,
    fontWeight: t.fontWeight ?? 400,
    color: t.color ?? '#111418',
    align: t.align ?? 'left',
    lineHeight: t.lineHeight ?? 1.2,
    letterSpacing: t.letterSpacing ?? 0,
    italic: t.italic ?? false,
  },
});

const shape = (
  s: Partial<ShapeStyle> & { x: number; y: number; width: number; height: number; rotation?: number },
): TemplateElement => ({
  type: 'shape',
  x: s.x,
  y: s.y,
  width: s.width,
  height: s.height,
  rotation: s.rotation ?? 0,
  content: {},
  style: {
    shape: s.shape ?? 'rect',
    fill: s.fill ?? '#12B5A9',
    radius: s.radius ?? 0,
  },
});

